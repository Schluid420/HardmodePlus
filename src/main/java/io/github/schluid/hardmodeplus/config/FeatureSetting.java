	public static FeatureSetting sectionSwitch(String section) {
		for (FeatureSetting setting : values()) {
			if (setting.section().equals(section) && setting.type == Type.SWITCH
					&& (setting.parent() == null || !setting.parent().section().equals(section))) {
				return setting;
			}
		}
		return null;
	}

	public static FeatureSetting byKey(String key) {
		for (FeatureSetting setting : values()) {
			if (setting.key.equals(key)) {
				return setting;
			}
		}
		return null;
	}

	public static List<FeatureSetting> inGroup(Group group) {
		List<FeatureSetting> list = new ArrayList<>();
		for (FeatureSetting setting : values()) {
			if (setting.group == group) {
				list.add(setting);
			}
		}
		return list;
	}
